import { build } from 'esbuild';
import sharp from 'sharp';
import { mkdir, copyFile, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const output = process.argv.includes('--dev') ? 'out' : 'dist';
await rm(join(root, output), { recursive: true, force: true });
await mkdir(join(root, output), { recursive: true });
await build({ absWorkingDir: root, entryPoints: { main: 'src/desktop/main.ts', 'backup-worker': 'src/app/backup-worker.ts', 'records-worker': 'src/app/records-worker.ts' }, outdir: output, outExtension: { '.js': '.mjs' }, bundle: true, splitting: true, chunkNames: 'node-[hash]', platform: 'node', format: 'esm', packages: 'external', target: 'node24' });
await build({ absWorkingDir: root, entryPoints: ['src/desktop/preload.ts'], outfile: `${output}/preload.cjs`, bundle: true, platform: 'node', format: 'cjs', external: ['electron'] });
await build({ absWorkingDir: root, entryPoints: { renderer: 'src/renderer/main.ts' }, outdir: output, splitting: true, chunkNames: 'web-[hash]', bundle: true, platform: 'browser', format: 'esm', target: 'chrome152' });
for (const name of ['index.html', 'style.css']) await copyFile(join(root, 'src', 'renderer', name), join(root, output, name));
await sharp(join(root, 'assets', 'picpatch.svg')).resize(512).png().toFile(join(root, output, 'icon.png'));
